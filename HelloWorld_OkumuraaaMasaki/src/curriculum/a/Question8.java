package curriculum.a;

public class Question8 {

    public static void main(String[] args) {

        // double型の変数 price を宣言して 99.99 を代入
        double price = 99.99;

        // price を int型に変換
        int intPrice = (int) price;

        // 結果を表示
        System.out.println("整数価格: " + intPrice);

    }
}